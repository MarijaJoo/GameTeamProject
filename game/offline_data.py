def build_scored_actions(
    wrong_start_id,
    correct_start_id,
    wrong_text,
    correct_text,
    wrong_messages,
    correct_messages,
):

    clue_points = [0, 5, 10, 15, 20]
    actions = []

    for index, points in enumerate(clue_points):
        actions.append(
            {
                "id": wrong_start_id + index,
                "action_text": wrong_text,
                "is_correct": False,
                "points_modifier": points - 5,
                "animal_message": wrong_messages[index],
            }
        )

    for index, points in enumerate(clue_points):
        actions.append(
            {
                "id": correct_start_id + index,
                "action_text": correct_text,
                "is_correct": True,
                "points_modifier": points + 10,
                "animal_message": correct_messages[index],
            }
        )

    return actions


